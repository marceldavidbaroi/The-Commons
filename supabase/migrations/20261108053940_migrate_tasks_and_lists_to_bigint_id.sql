-- 7. Counter Maintenance Trigger for `lists`
CREATE OR REPLACE FUNCTION public.sync_list_tasks_counts()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_list_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_list_id := OLD.list_id;
    ELSE
        v_list_id := NEW.list_id;
    END IF;

    -- Recalculate and update the counts on the associated list
    UPDATE public.lists
    SET
        live_tasks_count = (
            SELECT count(*)::integer
            FROM public.tasks
            WHERE list_id = v_list_id AND deleted_at IS NULL
        ),
        active_tasks_count = (
            SELECT count(*)::integer
            FROM public.tasks
            WHERE list_id = v_list_id
              AND deleted_at IS NULL
              AND status IN ('todo', 'in_progress')
        ),
        updated_at = now()
    WHERE id = v_list_id;

    -- If list_id changed on UPDATE
    IF TG_OP = 'UPDATE' AND OLD.list_id IS DISTINCT FROM NEW.list_id THEN
        UPDATE public.lists
        SET
            live_tasks_count = (
                SELECT count(*)::integer
                FROM public.tasks
                WHERE list_id = OLD.list_id AND deleted_at IS NULL
            ),
            active_tasks_count = (
                SELECT count(*)::integer
                FROM public.tasks
                WHERE list_id = OLD.list_id
                  AND deleted_at IS NULL
                  AND status IN ('todo', 'in_progress')
            ),
            updated_at = now()
        WHERE id = OLD.list_id;
    END IF;

    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_tasks_counter_sync
